CREATE TABLE reservation_process (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL,
    professional_id BIGINT NOT NULL,
    appointment_date DATE NOT NULL,
    start_time TIME(6) WITHOUT TIME ZONE NOT NULL,
    external_patient_id VARCHAR(100) NOT NULL,
    hold_id TEXT,
    external_reservation_process_id TEXT,
    process_status VARCHAR(50) NOT NULL DEFAULT 'PENDING_HOLD',
    expires_at TIMESTAMP WITH TIME ZONE,
    created_by VARCHAR(50) NOT NULL,
    created_date TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_modified_by VARCHAR(50),
    last_modified_date TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_reservation_process_owner FOREIGN KEY (owner_user_id)
        REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT uq_reservation_process_hold_id UNIQUE (hold_id),
    CONSTRAINT uq_reservation_process_external_id UNIQUE (external_reservation_process_id),
    CONSTRAINT chk_reservation_process_patient_owner
        CHECK (external_patient_id = 'user-' || owner_user_id::text),
    CONSTRAINT chk_reservation_process_status CHECK (process_status IN ('PENDING_HOLD', 'HELD')),
    CONSTRAINT chk_reservation_process_hold_not_blank
        CHECK (hold_id IS NULL OR length(btrim(hold_id)) > 0),
    CONSTRAINT chk_reservation_process_external_id_not_blank
        CHECK (external_reservation_process_id IS NULL OR length(btrim(external_reservation_process_id)) > 0),
    CONSTRAINT chk_reservation_process_held_details CHECK (
        process_status <> 'HELD' OR
        (hold_id IS NOT NULL AND external_reservation_process_id IS NOT NULL AND expires_at IS NOT NULL)
    ),
    CONSTRAINT chk_reservation_process_created_by CHECK (length(btrim(created_by)) > 0),
    CONSTRAINT chk_reservation_process_modified_by
        CHECK (last_modified_by IS NULL OR length(btrim(last_modified_by)) > 0),
    CONSTRAINT chk_reservation_process_modification_audit
        CHECK ((last_modified_by IS NULL) = (last_modified_date IS NULL))
);

CREATE INDEX ix_reservation_process_owner ON reservation_process (owner_user_id);
