CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(50) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    first_name VARCHAR(50),
    last_name VARCHAR(50),
    email VARCHAR(254) NOT NULL,
    image_url VARCHAR(256),
    lang_key VARCHAR(10) NOT NULL,
    activated BOOLEAN NOT NULL DEFAULT FALSE,
    created_by VARCHAR(50) NOT NULL,
    created_date TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_modified_by VARCHAR(50),
    last_modified_date TIMESTAMP WITH TIME ZONE,
    CONSTRAINT chk_app_user_login_not_blank CHECK (length(btrim(login)) > 0),
    CONSTRAINT chk_app_user_email_length CHECK (length(btrim(email)) >= 5),
    CONSTRAINT chk_app_user_lang_key_length CHECK (length(lang_key) >= 2),
    CONSTRAINT chk_app_user_created_by_not_blank CHECK (length(btrim(created_by)) > 0)
);

CREATE UNIQUE INDEX ux_app_user_login_lower ON app_user (lower(login));
CREATE UNIQUE INDEX ux_app_user_email_lower ON app_user (lower(email));

CREATE TABLE authority (
    name VARCHAR(50) PRIMARY KEY,
    CONSTRAINT chk_authority_name_not_blank CHECK (length(btrim(name)) > 0)
);

CREATE TABLE app_user_authority (
    user_id BIGINT NOT NULL,
    authority_name VARCHAR(50) NOT NULL,
    PRIMARY KEY (user_id, authority_name),
    CONSTRAINT fk_app_user_authority_user FOREIGN KEY (user_id)
        REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_app_user_authority_authority FOREIGN KEY (authority_name)
        REFERENCES authority (name)
);

CREATE INDEX ix_app_user_authority_authority ON app_user_authority (authority_name);

